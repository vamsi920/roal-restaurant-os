// Rebuilds the static import indexes for generated content and keeps the blog publish schedule.
// Run after generate-posts / generate-pages: npx tsx scripts/seo/build-content-index.ts
//
// Publish schedule (content/blog/_schedule.json, slug -> YYYY-MM-DD) is stable: existing slugs keep
// their date. New slugs get the next open day, LAUNCH_BATCH on the first day and PER_DAY after that,
// interleaved across categories so every day mixes topics. Posts go live on their date (ISR).
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

const BLOG_DIR = "content/blog";
const SCHEDULE_FILE = `${BLOG_DIR}/_schedule.json`;
const LAUNCH_DAY = "2026-10-28";
const LAUNCH_BATCH = 120;
const PER_DAY = 10;

type Post = { slug: string; category: string; keyword: string; title: string };

const addDays = (iso: string, n: number) => {
  const d = new Date(`${iso}T12:00:00Z`);
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
};

function interleave(posts: Post[]): Post[] {
  const byCat = new Map<string, Post[]>();
  for (const p of posts) byCat.set(p.category, [...(byCat.get(p.category) ?? []), p]);
  const lists = [...byCat.values()];
  const out: Post[] = [];
  for (let i = 0; out.length < posts.length; i++) for (const l of lists) if (l[i]) out.push(l[i]);
  return out;
}

function schedule(posts: Post[]) {
  const sched: Record<string, string> = existsSync(SCHEDULE_FILE) ? JSON.parse(readFileSync(SCHEDULE_FILE, "utf8")) : {};
  const counts = new Map<string, number>();
  for (const d of Object.values(sched)) counts.set(d, (counts.get(d) ?? 0) + 1);
  const capacity = (d: string) => (d === LAUNCH_DAY ? LAUNCH_BATCH : PER_DAY);
  let day = LAUNCH_DAY;
  for (const p of interleave(posts.filter((p) => !sched[p.slug]))) {
    while ((counts.get(day) ?? 0) >= capacity(day)) day = addDays(day, 1);
    sched[p.slug] = day;
    counts.set(day, (counts.get(day) ?? 0) + 1);
  }
  for (const s of Object.keys(sched)) if (!posts.some((p) => p.slug === s)) delete sched[s];
  const sorted = Object.fromEntries(Object.entries(sched).sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0])));
  writeFileSync(SCHEDULE_FILE, JSON.stringify(sorted, null, 2) + "\n");
  return sorted;
}

const STOP = new Set("a an the and or for to of in on at your you how what why is are do does with by from vs can".split(" "));
const tokens = (s: string) => new Set(s.toLowerCase().split(/[^a-z0-9]+/).filter((w) => w.length > 2 && !STOP.has(w)));

function related(posts: Post[]): Record<string, string[]> {
  const tok = new Map(posts.map((p) => [p.slug, tokens(`${p.title} ${p.keyword}`)]));
  const out: Record<string, string[]> = {};
  for (const p of posts) {
    const mine = tok.get(p.slug)!;
    out[p.slug] = posts
      .filter((q) => q.slug !== p.slug)
      .map((q) => {
        let score = q.category === p.category ? 2 : 0;
        for (const w of tok.get(q.slug)!) if (mine.has(w)) score += 1;
        return { slug: q.slug, score };
      })
      .sort((a, b) => b.score - a.score || a.slug.localeCompare(b.slug))
      .slice(0, 5)
      .map((x) => x.slug);
  }
  return out;
}

function ident(i: number) {
  return `p${i}`;
}

function main() {
  const files = readdirSync(BLOG_DIR).filter((f) => f.endsWith(".json") && !f.startsWith("_")).sort();
  const posts: Post[] = files.map((f) => JSON.parse(readFileSync(`${BLOG_DIR}/${f}`, "utf8")));
  const sched = schedule(posts);
  writeFileSync(`${BLOG_DIR}/_related.json`, JSON.stringify(related(posts), null, 2) + "\n");

  const blogIndex = [
    "// Generated by scripts/seo/build-content-index.ts. Do not edit by hand.",
    'import type { GeneratedPostJson } from "./generated-types";',
    'import schedule from "@/content/blog/_schedule.json";',
    'import related from "@/content/blog/_related.json";',
    ...files.map((f, i) => `import ${ident(i)} from "@/content/blog/${f}";`),
    "",
    `export const GENERATED_POST_JSON = [${files.map((_, i) => ident(i)).join(", ")}] as GeneratedPostJson[];`,
    "export const GENERATED_SCHEDULE = schedule as Record<string, string>;",
    "export const GENERATED_RELATED = related as Record<string, string[]>;",
    "",
  ].join("\n");
  writeFileSync("lib/blog/generated-index.ts", blogIndex);

  const families = ["for", "use-cases", "compare", "locations"];
  const lines = [
    "// Generated by scripts/seo/build-content-index.ts. Do not edit by hand.",
    'import type { LandingPageJson, GlossaryEntryJson } from "./landing-types";',
  ];
  const exportsByFamily: Record<string, string[]> = {};
  let n = 0;
  for (const fam of families) {
    const dir = `content/pages/${fam}`;
    const list = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".json")).sort() : [];
    exportsByFamily[fam] = [];
    for (const f of list) {
      const id = `g${n++}`;
      lines.push(`import ${id} from "@/content/pages/${fam}/${f}";`);
      exportsByFamily[fam].push(id);
    }
  }
  const hasGlossary = existsSync("content/glossary.json");
  if (hasGlossary) lines.push('import glossary from "@/content/glossary.json";');
  lines.push("");
  lines.push("export const LANDING_JSON: Record<string, LandingPageJson[]> = {");
  for (const fam of families) lines.push(`  "${fam}": [${exportsByFamily[fam].join(", ")}] as LandingPageJson[],`);
  lines.push("};");
  lines.push(`export const GLOSSARY_JSON = ${hasGlossary ? "glossary" : "[]"} as GlossaryEntryJson[];`);
  lines.push("");
  writeFileSync("lib/seo/generated-pages.ts", lines.join("\n"));

  const live = Object.values(sched).filter((d) => d <= new Date().toISOString().slice(0, 10)).length;
  console.log(`${posts.length} posts indexed (${live} live today, last scheduled ${Object.values(sched).at(-1)})`);
  console.log(`pages: ${families.map((f) => `${f} ${exportsByFamily[f].length}`).join(", ")}; glossary ${hasGlossary ? "yes" : "no"}`);
}

main();
